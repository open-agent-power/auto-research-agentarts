"""Run one isolated synthetic recipe-selection pilot through the existing CLI."""
import argparse
import copy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sqlite3
import subprocess
import sys
import time

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from autoresearch.contracts import ResearchError, canonical, fingerprint
from autoresearch.project_selection import validate_proposal
from autoresearch.research_project import code_identity, safe_path
from autoresearch.project_controller import code_identity as controller_identity

FIXTURE = b"record_id,batch,value\nr1,A,0\nr2,A,2\nr3,B,3\nr4,B,4\nr5,C,0\nr6,C,6\nr7,D,7\nr8,D,8\n"
GROUPED = "data.grouped-quality-profile"
SOURCE = "research.source-selection"


def write_json(path, value):
    with path.open("xb") as stream:
        stream.write((canonical(value) + "\n").encode("utf-8"))


def check(condition, message):
    if not condition:
        raise ResearchError("RECIPE_PILOT_FAILED", message)


class Pilot:
    def __init__(self, root):
        self.root = root
        self.commands = []

    def command(self, stage, script, *args):
        argv = [sys.executable, str(REPO / "scripts" / script), *map(str, args)]
        record = {"stage": stage, "argv": argv, "cwd": str(REPO)}
        self.commands.append(record)
        start = time.perf_counter()
        try:
            process = subprocess.run(argv, cwd=REPO, capture_output=True, timeout=60)
        except subprocess.TimeoutExpired as error:
            record.update(exit_code=None, timed_out=True, elapsed_seconds=time.perf_counter() - start)
            (self.root / (stage + ".stdout.json")).write_bytes(error.stdout or b"")
            (self.root / (stage + ".stderr.txt")).write_bytes(error.stderr or b"")
            raise ResearchError("PILOT_COMMAND_TIMEOUT", "Inspect partial state; do not restart in a new directory.") from None
        record.update(exit_code=process.returncode, elapsed_seconds=time.perf_counter() - start)
        (self.root / (stage + ".stdout.json")).write_bytes(process.stdout)
        (self.root / (stage + ".stderr.txt")).write_bytes(process.stderr)
        check(process.returncode == 0, "Command failed at " + stage + "; original output is preserved.")
        return json.loads(process.stdout)

    def project(self, stage, command, *args):
        return self.command(stage, "run_research_project.py", command, *args)

    def run(self):
        root = self.root
        fixture_dir = root / "input"
        fixture_dir.mkdir()
        (fixture_dir / "fixture.csv").write_bytes(FIXTURE)
        fixture_sha = hashlib.sha256(FIXTURE).hexdigest()
        uri = "urn:autoresearch:synthetic:research-recipe-v1:" + fixture_sha
        write_json(fixture_dir / "spec.json", {
            "schema_version": "tabular-quality-spec-v1", "file": "fixture.csv",
            "dataset_label": "Synthetic eight-row recipe engineering fixture v1",
            "source_url": uri, "license_note": "Original synthetic fixture supplied by this repository; no third-party data.",
            "sample_unit": "人工构造行，不代表独立实验", "group_columns": ["batch"],
            "key_columns": ["record_id"], "numeric_columns": ["value"],
            "target_column": None, "target_unit": None, "missing_tokens": ["", "NA"], "delimiter": ",",
            "provenance": {"origin_sha256": fixture_sha, "description": "Exact synthetic CSV bytes generated by verify_research_recipe.py; no upstream scientific data."},
        })
        recipe_paths = {label: REPO / "examples/research-recipes" / ("tabular-" + label + ".json")
                        for label in ("group-first", "source-first")}
        files = [Path(__file__), REPO / "src/autoresearch/research_recipe.py",
                 REPO / "scripts/compile_research_recipe.py", *recipe_paths.values()]
        write_json(root / "protocol.json", {
            "schema_version": "recipe-pilot-protocol-v1", "fixture": "synthetic_not_scientific_evidence",
            "started_at_utc": datetime.now(timezone.utc).isoformat(), "fixture_sha256": fixture_sha,
            "project_code_identity": code_identity(), "controller_code_identity": controller_identity(),
            "implementation_sha256": {str(path.relative_to(REPO)): hashlib.sha256(path.read_bytes()).hexdigest() for path in files},
            "order": "prepare-source/create/step/evidence-task/register-evidence/selection-context/compile-both/advance-selection/replay/status",
            "expected": {"rows": 8, "groups": 4, "finite": 8, "zeros": 2,
                         "zero_group_labels": ["A", "C"], "local_tool_calls": 2, "source_reads": 0},
            "failure_criteria": ["No simultaneous legal grouped and unread-source candidates", "Recipes select the same or unexpected action",
                                 "Either proposal fails original validation", "Execution or replay adds unexpected actions, reads or costs", "Counts differ from fixture"],
            "limits": {"local_tool_calls": 2, "model_calls": 0, "new_fits": 0, "paid_calls": 0},
            "scientific_validation": False,
        })
        source = root / "captured/source.json"
        project = root / "project"
        self.project("01-prepare", "prepare-source", "--method", "data.tabular-quality-audit", "--input", fixture_dir, "--output", source)
        self.project("02-create", "create", "--method", "data.tabular-quality-audit", "--source", source,
                     "--workspace", project, "--goal", "Synthetic engineering pilot: choose grouping or an unread fixture source after two zeros.",
                     "--budget-ref", "teammate-recipe-task:2026-11-03:isolated-synthetic-two-tools", "--max-tool-calls", 2)
        primary = self.project("03-primary", "step", "--workspace", project, "--request-id", "recipe-primary-1")
        primary_artifact = json.loads((project / primary["artifact"]).read_bytes())
        primary_result = primary_artifact["tool_result"]["result"]["profile"]
        check(primary_result["rows"] == 8 and primary_result["group_columns"]["group_count"] == 4,
              "Primary counts differ from the frozen fixture.")
        counts = primary_result["numeric_columns"][0]["counts"]
        check(counts == {"finite": 8, "zero": 2, "empty": 0, "declared_missing": 0, "invalid_numeric": 0, "nonfinite": 0},
              "Primary numeric counts differ from the frozen fixture.")
        task = self.project("04-task", "evidence-task", "--workspace", project)
        bundle = root / "bundle"
        (bundle / "sources").mkdir(parents=True)
        raw = ("Synthetic fixture generated by verify_research_recipe.py; source identity " + uri + ".\n"
               "人工构造夹具不能证明样本独立性。Batch A/B/C/D are constructed labels; zero meaning is not a scientific conclusion.\n").encode("utf-8")
        (bundle / "sources/source.txt").write_bytes(raw)
        manifest = copy.deepcopy(task["manifest_template"])
        manifest.update(contributor={"role": "operator_assistant", "label": "Deterministic synthetic recipe pilot"},
                        sources=[{"id": "fixture-origin", "path": "sources/source.txt", "sha256": hashlib.sha256(raw).hexdigest(),
                                  "url": uri, "media_type": "text/plain", "license_note": "Original synthetic fixture note; no third-party content."}],
                        selections=[{"id": "independence-limit", "source_id": "fixture-origin", "locator": {"kind": "text_lines", "value": "1-2"},
                                     "claim": "Constructed rows and batch labels do not prove independent scientific samples."}],
                        remaining_questions=["Scientific zero coding and independence do not follow from a constructed fixture."])
        write_json(bundle / "manifest.json", manifest)
        self.project("05-register", "register-evidence", "--workspace", project, "--request-id", "recipe-register-1", "--bundle", bundle)
        return self.finish(project, primary_artifact)

    def finish(self, project, primary_artifact):
        """Continue after registration; also reusable for an inspected local pilot repair."""
        root = self.root
        recipe_paths = {label: REPO / "examples/research-recipes" / ("tabular-" + label + ".json")
                        for label in ("group-first", "source-first")}
        before = self.project("06-before", "status", "--workspace", project)
        context = self.project("07-context", "selection-context", "--workspace", project, "--need", "next_check")
        write_json(root / "context.json", context)
        frozen_sha = hashlib.sha256((root / "context.json").read_bytes()).hexdigest()
        methods = [candidate["method_id"] for candidate in context["candidates"]]
        check(not context["blockers"] and methods.count(GROUPED) == 1 and methods.count(SOURCE) == 1,
              "Frozen context does not contain both legal candidates; inspect 07-context.stdout.json conditions/candidates/blockers.")
        check(before["budget"]["local_tool_calls_used"] == 1 and before["budget"]["evidence_reads_used"] == 0
              and not before["evidence_actions"], "Registration unexpectedly executed a tool or extracted a source.")
        decisions = {}
        for label, recipe_path in recipe_paths.items():
            self.command("08-compile-" + label, "compile_research_recipe.py", "--recipe", recipe_path,
                         "--context", root / "context.json", "--output", root / label)
            decisions[label] = json.loads((root / label / "decision.json").read_bytes())
        proposals = {label: json.loads((root / label / "proposal.json").read_bytes()) for label in decisions}
        selected = {label: validate_proposal(context, proposal)["candidate"] for label, proposal in proposals.items()}
        check(selected["group-first"]["method_id"] == GROUPED and selected["source-first"]["method_id"] == SOURCE,
              "Recipe order did not change the selected method as expected.")
        check(selected["group-first"]["id"] != selected["source-first"]["id"], "Expected distinct candidate IDs.")
        arguments = ("--workspace", project, "--request-id", "recipe-grouped-1", "--proposal", root / "group-first/proposal.json",
                     "--need", "next_check", "--expected-state-version", context["state_version"])
        execution = self.project("09-execute", "advance-selection", *arguments)
        after = self.project("10-after", "status", "--workspace", project)
        replay = self.project("11-replay", "advance-selection", *arguments)
        final = self.project("12-final", "status", "--workspace", project)
        check(execution["status"] == "completed" and replay["replayed"] is True
              and replay["child_request_id"] == execution["child_request_id"], "Execution/replay did not preserve the original child.")
        check(after["snapshot_ref"] == final["snapshot_ref"] and after["state_version"] == final["state_version"],
              "Exact replay changed the project snapshot or state version.")
        check(len(final["actions"]) == 2 and not final["evidence_actions"]
              and final["budget"]["local_tool_calls_used"] == 2 and final["budget"]["local_tool_call_limit"] == 2
              and final["budget"]["evidence_reads_used"] == 0, "Unexpected cumulative tool or source usage.")
        action = next(item for item in final["actions"] if item["command"] == GROUPED)
        envelope = json.loads((project / action["artifact"]).read_bytes())
        result = envelope["tool_result"]["result"]
        summary = result["summary"]
        zero = summary["numeric_columns"][0]["concentration"]["zero"]
        check(summary["rows"] == 8 and summary["group_count"] == 4 and zero["total"] == 2
              and zero["affected_groups"] == 2 and zero["max_group_count"] == 1, "Grouped counts differ from the fixture.")
        for label in "ABCD":
            group = next(item for item in result["groups"] if item["group_id"] == "group-" + fingerprint([label]))
            check(group["rows"] == 2 and group["numeric_counts"][0] == [2, int(label in "AC"), 0, 0, 0, 0],
                  "Unexpected numeric counts for constructed batch " + label)
        for artifact in (primary_artifact, envelope):
            check(artifact["tool_result"]["new_fits"] == 0 and artifact["tool_result"]["model_calls"] == 0,
                  "Unexpected model or fit usage.")
        check(hashlib.sha256((root / "context.json").read_bytes()).hexdigest() == frozen_sha, "Frozen context file changed.")
        results = {"ok": True, "schema_version": "recipe-pilot-results-v1", "fixture": "synthetic_not_scientific_evidence",
                   "context_sha256": context["context_sha256"], "context_file_sha256": frozen_sha,
                   "eligible_candidates": len(context["candidates"]), "selected_methods": {key: value["method_id"] for key, value in selected.items()},
                   "original_validator_passed": ["group-first", "source-first"], "executed_method": GROUPED,
                   "replay_added_actions": len(final["actions"]) - len(after["actions"]), "replay_snapshot_unchanged": True,
                   "local_tool_calls": 2, "source_reads": 0, "model_calls": 0, "new_fits": 0, "paid_calls": 0,
                   "grouped_summary": summary, "scientific_validation": False,
                   "historical_costs": "unknown; not reset or imported", "budget": final["budget"]}
        write_json(root / "results.json", results)
        return results


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, help="New isolated output directory; never overwrites an earlier pilot.")
    args = parser.parse_args()
    pilot = None
    try:
        root = safe_path(Path(args.output).absolute())
        if root.exists():
            raise ResearchError("OUTPUT_EXISTS", "Preserve the existing pilot; choose no replacement for a failed run without inspecting its evidence.")
        root.mkdir(parents=True)
        pilot = Pilot(root)
        results = pilot.run()
        write_json(root / "commands.json", pilot.commands)
        print(json.dumps({"ok": True, "output": str(root), "context_sha256": results["context_sha256"],
                          "local_tool_calls": results["local_tool_calls"], "source_reads": results["source_reads"],
                          "replay_added_actions": results["replay_added_actions"], "scientific_validation": False}))
        return 0
    except (ResearchError, OSError, ValueError, KeyError, StopIteration, sqlite3.Error) as error:
        failure = {"ok": False, "code": getattr(error, "code", "RECIPE_PILOT_FAILED"), "message": str(error),
                   "scientific_validation": False, "notice": "Partial outputs and original project retained; no automatic rerun or budget reset."}
        if pilot is not None:
            write_json(pilot.root / "commands.json", pilot.commands)
            write_json(pilot.root / "failure.json", failure)
        print(json.dumps(failure, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
