import { build } from "esbuild";
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(root, "../src/autoresearch/web");
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/app.ts"],
  outfile: path.join(output, "app.js"),
  bundle: true,
  platform: "browser",
  format: "iife",
  target: ["es2022"],
  supported: { "template-literal": false },
  minify: true,
  sourcemap: false,
  metafile: true,
  legalComments: "none",
  charset: "utf8",
  plugins: [{
    name: "browser-global-without-dynamic-function",
    setup(builder) {
      // lodash's generic environment fallback uses Function; this target is ES2022 browsers.
      builder.onLoad({ filter: /node_modules[\\/]lodash-es[\\/]_root\.js$/ }, () => ({
        contents: "export default globalThis;",
        loader: "js",
      }));
    },
  }],
});
const used = new Set();
for (const artifact of Object.values(result.metafile.outputs)) {
  for (const [name, info] of Object.entries(artifact.inputs)) {
    if (info.bytesInOutput > 0 && name.includes("node_modules/")) used.add(name);
  }
}
const packages = new Map();
for (const name of used) {
  let folder = path.dirname(path.resolve(root, name));
  while (folder.startsWith(path.join(root, "node_modules"))) {
    try {
      const metadata = JSON.parse(await readFile(path.join(folder, "package.json"), "utf8"));
      if (metadata.name && metadata.version) {
        packages.set(metadata.name, { ...metadata, folder });
        break;
      }
    } catch {}
    folder = path.dirname(folder);
  }
}
const notices = ["Browser bundle third-party notices", "Generated by frontend/build.mjs from actual emitted browser inputs.", "Build tools are not browser dependencies.", ""];
for (const [name, metadata] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const names = (await readdir(metadata.folder)).filter((file) => /^(licen[sc]e|copying|notice|copyright)(?:[._-].*)?$/i.test(file)).sort();
  if (!names.length) throw new Error("Missing license notice for emitted dependency: " + name);
  notices.push("=".repeat(72), name + "@" + metadata.version, "SPDX: " + (metadata.license || "see notices"), "");
  for (const file of names) notices.push(file, (await readFile(path.join(metadata.folder, file), "utf8")).replace(/\r\n?/g, "\n"), "");
}
for (const name of ["app.js", "app.css"]) {
  const file = path.join(output, name);
  const value = (await readFile(file, "utf8")).replace(/\r\n?/g, "\n");
  if (name === "app.js" && (/\beval\s*\(/.test(value) || /\bFunction\s*\(/.test(value))) {
    throw new Error("Dynamic script evaluation is not allowed in the browser bundle");
  }
  await writeFile(file, value, "utf8");
}
await writeFile(path.join(output, "index.html"), (await readFile(path.join(root, "index.html"), "utf8")).replace(/\r\n?/g, "\n"), "utf8");
await writeFile(path.join(output, "vendor-licenses.txt"), notices.join("\n") + "\n", "utf8");
console.log(JSON.stringify({ output: "src/autoresearch/web", files: ["index.html", "app.js", "app.css", "vendor-licenses.txt"], browser_dependencies: [...packages.keys()].sort(), engine: "@antv/x6@3.1.8" }));

